; L10MEM.ASM   第 10 课   直接写显存: 黑进去, 在屏幕上"画"字
;---------------------------------------------------------------------
; 本课知识点 (很像"黑客"的一课, 也是课程实验最爱考的):
;   1. 文本模式下显存规矩的地址是 B800:0000 开始的一块内存:
;        每行 80 个字符, 每个字符占 2 个字节:
;          偶数偏移 = 字符本身(ASCII)
;          奇数偏移 = 属性字节
;        某行某列的地址 = 行号×160 + 列号×2   (行、列从 0 开始数)
;   2. 属性字节: 高 4 位背景色, 低 4 位前景色
;        07h = 黑底白字, 1Eh = 蓝底黄字, 4Eh = 红底白字
;   3. ES 段寄存器: 访问 B800 段要 mov ax,0b800h / mov es,ax
;      (mov es:[di],ax 一次性把 AL 的字符 + AH 的属性写到两个字节里)
;   4. int 10h: 0 号功能 "BIOS 显示中断" 的常用套路 —— 6 号清屏/滚屏,
;      2 号定位光标 (DH=行 DL=列)
;---------------------------------------------------------------------
; 运行结果:
;   屏幕先被清空, 中间一行出现蓝底黄字: WELCOME TO 8086 ASM!
;   左下角有句普通文字提示 (这句是 9 号功能打的, 处于光标位置)
;---------------------------------------------------------------------
; 练习:
;   (1) 把颜色改成红底白字 (属性 4Eh), 重新编译跑一遍看效果
;   (2) 在字符串前后各画两个 '*' 当边框 (想想怎么调整长度和起点)
;   (3) 挑战: 把整个第 12 行 (0 基的 11 行) 全部刷成蓝色背景空格,
;       再做居中文字 —— 就是"横幅大字报"
;   (4) 思考: 为什么平时我们用 9 号功能打印就行, 什么时候才需要碰显存?
;       (提示: 颜色/速度/不用滚动的时候)
;=====================================================================

data segment
     msg  db 'WELCOME TO 8086 ASM!'     ; 正好 20 个字符
     hint db 'Look at the middle of the screen! (this line is DOS output)$'
     hextab db '0123456789ABCDEF'       ; 备用: 想在屏幕上打地址可以查表
data ends

code segment
     assume cs:code, ds:data
start:
     mov ax, data
     mov ds, ax

     ;---- 1. 清屏: int 10h 6号功能 = 从左上滚到右下(全屏刷空) ----
     mov ah, 6                          ; 6 号: 滚屏(给 al=0 就是清屏)
     mov al, 0                          ; 滚 0 行 = 整屏刷干净
     mov bh, 7                          ; 刷成什么属性: 7 = 黑底白字
     mov cx, 0                          ; 左上角 (第0行第0列)
     mov dx, 184fh                      ; 右下角 (第24行第79列) 18h=24,4fh=79
     int 10h

     ;---- 2. 把字符串画到第 11 行(0基), 水平居中 ----------------
     ;   地址 = 11×160 + 30×2 = 1760 + 60 = 1820
     ;   居中的 30 是这么算的: (80 - 20字符) ÷ 2 = 30
     mov ax, 0b800h                     ; ★显存段基址
     mov es, ax
     mov di, 1820                       ; ES:DI 指向目标位置

     mov si, offset msg
     mov cx, 20                         ; 20 个字符
     mov ah, 1eh                        ; ★属性字节: 1Eh = 蓝底黄字
write_loop:
     mov al, [si]                       ; AL = 字符
     mov es:[di], ax                    ; ★一次写 2 字节: 低字节字符, 高字节属性
                                        ;   (小端序正好把 AL 放低地址, AH 放高地址)
     add di, 2                          ; 下一格
     inc si
     loop write_loop

     ;---- 3. 光标回到左下角, 用普通的 9 号功能打个提示 -----------
     mov ah, 2                          ; 2 号: 定位光标
     mov bh, 0                          ; 0 页
     mov dx, 1800h                      ; DH=24 (最后一行), DL=0 (最左)
     int 10h

     mov dx, offset hint
     mov ah, 9
     int 21h

     mov ah, 4ch
     int 21h
code ends
end start

