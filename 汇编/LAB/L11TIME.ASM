;=====================================================================
; L11TIME.ASM   第 11 课   跟系统要时间: int 21h 2Ch 与补零打印
;---------------------------------------------------------------------
; 本课知识点:
;   1. int 21h 2Ch 功能: 取系统时间, 一次给你四个值 ——
;        CH = 时, CL = 分, DH = 秒, DL = 百分秒
;      ★一个 16 位寄存器装两个值: CX 里是"时分", DX 里是"秒+百分秒"
;      (考试必考: 问你哪个值藏在哪个寄存器里)
;   2. 取日期是 2Ah 功能: CX=年, DH=月, DL=日, AL=星期几 (顺便记一下)
;   3. ★补零打印技巧: 9 分 5 秒 要显示成 09:05:00, 不是 9:5:0!
;      做法: 先算出十位和个位两个数字, 十位即使是 0 也老老实实打印
;      (对比 L06 那个"十位是 0 就补空格"的技巧, 一个是补零一个是补空格)
;   4. 子程序 print2: AL 里给 0~99 的数, 打印成两位十进制 (自动补零)
;---------------------------------------------------------------------
; 运行结果 (每次跑都不一样, 显示的是真实系统时间):
;   Time now: 19:24:07
;---------------------------------------------------------------------
; 练习:
;   (1) 把秒的百分位也显示出来, 凑成 "HH:MM:SS + 两位百分秒" 的完整格式
;   (2) 再加一行显示日期 (2Ah 功能): "Date: 2026-10-13 星期X"
;   (3) 挑战: 让它循环刷新, 变成会走的表 —— 完整的电子钟在 PROJ/P3CLOCK
;   (4) 思考: 打印用的 int 21h 会改 AX, 而时间刚取回来在 CX/DX 里 ——
;       我们为什么可以放心打印? (提示: 那 CX/DX 呢?)
;=====================================================================

;---- 有 call, 就有栈 ----
stack segment stack
     db 200h dup(0)
stack ends

data segment
     pre   db 'Time now: $'
     crlf  db 0dh,0ah,'$'
     hour    db 0                         ; 存"时"
     minu    db 0                         ; 存"分"
     secs    db 0                         ; 存"秒"
data ends

code segment
     assume cs:code, ds:data
start:
     mov ax, data
     mov ds, ax

     ;---- 1. 取时间 (2Ch) ---------------------------------------
     mov ah, 2ch
     int 21h                            ; 返回: CH=时 CL=分 DH=秒 DL=百分秒

     ;---- 2. 先把三个值全部存到内存变量里 ------------------------
     ;   ★为什么这么急? 因为接下来任何 int 21h 都可能动 CX/DX,
     ;     趁热把数据舀进自己的碗里 (变量), 后面随便折腾
     mov hour, ch
     mov minu, cl
     mov secs, dh

     ;---- 3. 打印 "Time now: " ----------------------------------
     mov dx, offset pre
     call printstr

     ;---- 4. 按 HH:MM:SS 格式打印 --------------------------------
     mov al, hour
     call print2                        ; 时
     mov dl, ':'
     mov ah, 2
     int 21h
     mov al, minu
     call print2                        ; 分
     mov dl, ':'
     mov ah, 2
     int 21h
     mov al, secs
     call print2                        ; 秒

     mov dx, offset crlf
     call printstr

     mov ah, 4ch
     int 21h

;=====================================================================
; print2 -- 把 AL 里的 0~99 打印成两位十进制, 十位是 0 也照样打印
;   入口: AL = 0~99
;   例:   AL=7 → 显示 "07";  AL=42 → 显示 "42"
;=====================================================================
print2:
     push ax
     push bx
     push dx

     mov ah, 0                          ; AX = 0~99 (高位清零, 为除法做准备)
     mov bl, 10
     div bl                             ; AL = 十位, AH = 个位
     push ax                            ; 个位存在 AH, 压栈保管
     mov dl, al
     add dl, '0'
     mov ah, 2
     int 21h                            ; ★打印十位 (0 也要打! 这就是补零)
     pop ax
     mov dl, ah
     add dl, '0'
     mov ah, 2
     int 21h                            ; 打印个位

     pop dx
     pop bx
     pop ax
     ret

;---- 通用打印字符串 ----
printstr:
     push ax
     mov ah, 9
     int 21h
     pop ax
     ret
code ends
end start

