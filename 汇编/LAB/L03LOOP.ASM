;=====================================================================
; L03LOOP.ASM   第 3 课   循环指令 loop 与嵌套循环的坑
;---------------------------------------------------------------------
; 本课知识点:
;   1. loop 标号 的完整执行过程: 先把 CX 减 1, 再判断 CX 是否为 0,
;      不为 0 就跳转, 为 0 就往下走 (所以循环次数 = 循环前 CX 的值)
;   2. 用 CX + loop 打印 A~Z
;   3. ★嵌套循环最大的坑: 内层 loop 会把外层计数的 CX 改掉!
;      解决办法: 外层计数换一个寄存器 (这里用 BL) 或把 CX 压栈保存
;---------------------------------------------------------------------
; 运行结果:
;   A B C D E ... Z  (26 个字母, 每个后面一个空格)
;   *
;   **
;   ***
;   ****
;   *****
;---------------------------------------------------------------------
; 练习:
;   (1) 把第一个循环改成打印 a~z
;   (2) 倒着打印 Z~A (提示: 从 'Z' 开始 dec)
;   (3) 三角形反过来, 打印"倒三角" (提示: 行号从 5 递减到 1)
;   (4) 挑战: 打印 8 行星号菱形 (上半三角形 1..4 行 + 下半倒三角 3..1 行)
;=====================================================================

data segment
     crlf db 0dh,0ah,'$'
data ends

code segment
     assume cs:code, ds:data
start:
     mov ax, data
     mov ds, ax

     ;=========================================================
     ; 任务 1: 打印 A B C ... Z
     ;=========================================================
     mov cx, 26                         ; ★循环次数放进 CX
     mov dl, 'A'                        ; 要打印的第一个字符
letter_loop:
     mov ah, 2                          ; 2 号功能: 显示 DL
     int 21h

     ;--- 打印一个空格 (02h 只认 DL, 所以要先把字母存起来) -----
     push dx                            ; 保存字母
     mov dl, ' '
     mov ah, 2
     int 21h
     pop dx                             ; 取回字母

     inc dl                             ; 下一个字母 (ASCII 码 +1)
     loop letter_loop                   ; ★CX 自动减 1, 不为 0 就跳回 letter_loop

     ; 结束后换行
     mov dx, offset crlf
     mov ah, 9
     int 21h

     ;=========================================================
     ; 任务 2: 打印 5 行星号三角形
     ;   第 1 行 1 个 '*', 第 2 行 2 个 ... 第 5 行 5 个
     ;=========================================================
     ; ★外层行号计数放在 BL 而不是 CX, 因为内层 loop 要用 CX!
     mov bl, 1                          ; BL = 当前行号, 从 1 开始

row_loop:
     ;--- 内层: 打印 BL 个星号 ---------------------------------
     mov cl, bl                         ; 内层循环次数 = 当前行号
     mov ch, 0                          ; ★别忘了把 CH 清 0, CX=CH:CL 才等于 BL
star_loop:
     mov dl, '*'
     mov ah, 2
     int 21h
     loop star_loop                     ; 打印一个星号, CX-1

     ;--- 本行打完, 换行 ---------------------------------------
     mov dx, offset crlf
     mov ah, 9
     int 21h

     inc bl                             ; 行号 +1
     cmp bl, 5
     jbe row_loop                       ; BL <= 5 就继续打下一行 (jbe = ≤)

     ;=========================================================
     mov ah, 4ch
     int 21h
code ends
end start

