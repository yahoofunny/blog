;=====================================================================
; L02KEY.ASM   第 2 课   键盘输入 + 大小写转换 (位运算的妙用)
;---------------------------------------------------------------------
; 本课知识点:
;   1. int 21h 1 号功能: 读一个字符, 结果在 AL (带回显, 也就是你敲什么屏幕显示什么)
;   2. int 21h 2 号功能: 把 DL 里的字符显示到屏幕上
;   3. cmp + je/jb/ja 做条件分支 (有符号比较是 jg/jl, 这里用无符号这组)
;   4. ★位运算技巧:
;        大写字母 AND 11011111b → 变小写
;        小写字母 OR  00100000b → 变大写  (第 5 位 bit5 是"大小写开关")
;      字符 'A'=41h, 'a'=61h, 正好差 20h = 0010 0000b
;   5. 循环结构: 标号 + jmp 实现"无限循环", 直到命中退出条件
;---------------------------------------------------------------------
; 运行结果 (输入 a, B, 5, # 为例):
;   a -> A       (小写变大写)
;   B -> b       (大写变小写)
;   5 -> ?       (不是字母)
;   #            (退出) Bye!
;---------------------------------------------------------------------
; 练习:
;   (1) 输入小写字母时也把原字符先打印出来, 例如 "a->A"
;   (2) 改成只处理数字: 输入数字原样回显, 其他字符一律打印 '?' 
;   (3) 把退出条件从 '#' 改成回车 (13 = 0Dh), 提示: cmp al,0dh
;=====================================================================

data segment
     bye  db 0dh,0ah,'Bye!$'
     crlf db 0dh,0ah,'$'                ; 一个专门用来"打印机换行"的串
data ends

code segment
     assume cs:code, ds:data
start:
     mov ax, data
     mov ds, ax

loop_top:                               ; ★循环头
     ;---- 读一个字符 (1 号功能) --------------------------------
     mov ah, 1                          ; AH=1: 读字符, 你敲的字符会显示在屏幕上(回显)
     int 21h                            ; 返回后 AL = 你敲的字符的 ASCII 码

     cmp al, '#'                        ; 是不是退出符?
     je  quit                           ; je = jump if equal

     ;---- 判断小写字母 'a'..'z' --------------------------------
     cmp al, 'a'
     jb  not_lower                      ; jb = jump if below (无符号"小于")
     cmp al, 'z'
     ja  not_lower                      ; ja = jump if above (无符号"大于")

     ; 落在 'a'..'z' 区间: 变小写为大写 → 把 bit5 清 0
     ; 例: 'a' = 0110 0001b, AND 1101 1111b = 0100 0001b = 'A'
     mov dl, al
     and dl, 11011111b
     mov ah, 2                          ; AH=2: 显示 DL 中的字符
     int 21h
     jmp  next

not_lower:
     ;---- 判断大写字母 'A'..'Z' --------------------------------
     cmp al, 'A'
     jb  other                          ; 比 'A' 还小 → 别的字符
     cmp al, 'Z'
     ja  other                          ; 比 'Z' 还大 → 别的字符

     ; 是大写: 变大写为小写 → 把 bit5 置 1
     mov dl, al
     or  dl, 00100000b
     mov ah, 2
     int 21h
     jmp  next

other:
     ;---- 既不是小写也不是大写 --------------------------------
     mov dl, '?'
     mov ah, 2
     int 21h

next:
     ;---- 打印回车换行 (用 9 号功能打印 crlf 串) ---------------
     mov dx, offset crlf
     mov ah, 9
     int 21h
     jmp loop_top                       ; 回到循环头继续读下一个字符

quit:
     mov dx, offset bye                 ; 打印告别语
     mov ah, 9
     int 21h
     mov ah, 4ch
     int 21h
code ends
end start

