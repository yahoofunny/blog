; L01HI.ASM   第 1 课   你的第一个完整程序: Hello World
;---------------------------------------------------------------------
; 本课要弄懂的问题 (对应课程"汇编语言程序框架"):
;   1. data segment ... data ends 和 code segment ... code ends 是啥
;   2. 为什么 DS 必须手动加载: mov ax,data / mov ds,ax
;   3. int 21h 的 9 号功能: 打印以 '$' 结尾的字符串
;   4. int 21h 的 4Ch 功能: 程序返回 DOS
;   5. 入口标号 start 与末尾 end start 的对应关系
;---------------------------------------------------------------------
; 运行结果:
;   Hello World!
;   I am learning 8086!
;---------------------------------------------------------------------
; 练习 (改完重新编译, 看结果变了没有):
;   (1) 把第一句改成你的名字
;   (2) 再加一句第三行输出 (仿照 msg2 的写法)
;   (3) 把字符串结尾的 '$' 删掉, 编译运行, 看看会发生什么 —— 想想为什么
;   (4) 把 mov ah,9 改成 mov ah,2, 再运行 —— 为什么只输出一个字符?
;=====================================================================

data segment
     ; db = define byte, 定义字节数据
     ; 9 号功能要求字符串必须以 '$' 结尾, 否则会一直往后打印直到遇见 '$'
     msg  db 'Hello World!$'

     ; 0dh=回车(CR) 0ah=换行(LF), 这两个字节连用 = 屏幕上换到下一行行首
     msg2 db 0dh,0ah,'I am learning 8086!$'
data ends

code segment
     assume cs:code, ds:data        ; 告诉汇编器: code 段将来用 CS 访问, data 段用 DS 访问

start:                              ; ★程序入口, 与文件最后一行 end start 对应
     ;---- 第 1 步: 让 DS 指向 data 段 ------------------------------
     ; 8086 规定: 段寄存器不能用立即数直接赋值!
     ;     mov ds, data     ← 这是错的, MASM 会报错
     ; 所以标准套路是先经过 ax 中转:
     mov ax, data                   ; 取 data 段的段基址 → AX
     mov ds, ax                     ; DS = data 段基址, 此后 [偏移] 访问的就是 data 段

     ;---- 第 2 步: 用 9 号功能打印字符串 ---------------------------
     ; 9 号功能的规矩: 要打印的串地址必须放在 DX 里, AH 放功能号 9
     mov dx, offset msg             ; DX = msg 的偏移地址 (offset 取偏移)
     mov ah, 9                      ; AH = 9, 功能号
     int 21h                        ; 调用 DOS 中断干活

     ;---- 第 3 步: 打印第二行 -------------------------------------
     mov dx, offset msg2
     mov ah, 9
     int 21h

     ;---- 第 4 步: 返回 DOS ---------------------------------------
     ; 4Ch 号功能: 结束程序并把控制权还给 DOS
     ; 不写这步程序会"跑飞", 跑到段外面去执行乱七八糟的字节
     mov ah, 4ch
     mov al, 0                      ; AL = 返回值 (0 = 正常), 可省略
     int 21h
code ends

end start                           ; 声明: 程序从 start 标号开始执行
