#!/usr/bin/env bash
# =====================================================================
# quiz.sh -- 8086 汇编快问快答 (终端里刷题, 自动判分)
#
# 用法:  bash ~/asm/quiz.sh
# 玩法:  每题输入 A/B/C/D 回车; 直接回车 = 看答案(不计分); 中途输入 q 退出
# 题目:  24 道, 覆盖 寄存器/寻址/指令/标志位/中断/显存 等高频考点
# =====================================================================
set -u

# 题库: 题干|A|B|C|D|正确答案|解析
Q=(
"8086 中物理地址的计算公式是?|段地址 + 偏移地址|段地址 × 16 + 偏移地址|段地址 × 10 + 偏移地址|段地址 << 8 + 偏移地址|B|段基址要先左移 4 位(相当于乘16)再拼偏移"
"下列哪条指令是合法的?|mov ds, 1000h|mov cs, ax|mov ds, ax|mov es, 2000h|C|段寄存器不能收立即数, CS 不能当 mov 目的, 都得借通用寄存器中转"
"loop 指令的执行顺序是?|先判断再减1|先减1再判断|只减1不判断|只判断不减1|B|口诀: 先减后判。CX 从 5 走到 0 共循环 5 次"
"div bx 指令执行后, 商和余数分别在?|商在 AX, 余在 BX|商在 AX, 余在 DX|商在 DX, 余在 AX|商在 BX, 余在 DX|B|16位除法 DX:AX ÷ BX → 商 AX 余 DX; 8位除法才是 AL/AH"
"用 [bx] 遍历一个 dw 数组, 指针每次应该加?|1|2|4|不用加|B|dw 每个元素 2 字节, 所以 add bx,2"
"无符号数比较应该用哪组跳转?|jg / jl|jb / ja|je / jne|js / jns|B|jb/ja 看 CF; jg/jl 是有符号组, 拿 FFFFh 一测就分出区别"
"int 21h 的 9 号功能要求字符串以什么结尾?|数字 0|'\$' 字符|0Dh|不需要结尾|B|9 号功能认 '$'; 认 0 的是 C 语言习惯"
"执行 push 一个字时, SP 怎么变化?|SP 加 2|SP 减 2|SP 不变|SP 减 1|B|先 SP 减 2, 再写入; pop 相反"
"'a'(61h) 执行 and al, 0DFh 之后变成?|'A'|'a'|'\`'|0|A|61h AND DFh = 41h = 'A'; bit5 是大小写的开关"
"shl 左移一位时, 移出去的那一位进哪里?|直接丢失|OF|CF|ZF|C|最高位先进 CF; 想按位打印二进制就靠它"
"xlat 查表指令要求表地址放在哪个寄存器?|AX|BX|CX|DX|B|xlat: AL = DS:[BX+AL], 表首地址在 BX, 下标在 AL"
"执行 call 标号时, CPU 自动做了什么?|清零 AX|把返回地址压栈|保存所有寄存器|切换段寄存器|B|ret 就是把它弹回来 —— 这就是子程序的全部秘密"
"int 21h 的 4Ch 号功能是干什么的?|读取字符|显示字符串|结束程序返回 DOS|清屏|C|不写这句程序会跑飞到段外 —— 每份作业的必备结尾"
"文本模式下显存 B800 一行占多少字节?|80|160|320|25|B|80 个字符 × 每字符 2 字节(字符+属性) = 160"
"属性字节 1Eh 的显示效果是?|黑底白字|蓝底黄字|红底白字|白底黑字|B|高4位背景=1蓝, 低4位前景=E黄; 07 是黑底白字"
"0Ah 输入缓冲区的第 2 个字节存放什么?|缓冲区最大长度|实际输入的长度|第一个字符|回车符|B|buf+1 是实际长度, 内容从 buf+2 开始 —— 解析输入必用"
"loop 指令当 CX 初值为 0 时, 循环体会执行几次?|0 次|1 次|65536 次|恰好 128 次|C|先减 1 变成 FFFFh 非 0 → 一直转到 CX 归零"
"cmp a, b 的本质是?|做减法并把结果存回 a|做减法但只改标志位|做加法|只改 IP|B|所以 cmp 后面必须跟条件跳转来看结果"
"8086 的条件跳转(jcc)能跳多远?|任意远|±127 字节以内|±32767 字节|固定 128 字节|B|8086 只有短条件跳; 跳太远会报 Jump out of range, 用 jmp 接力"
"int 16h 的 01h 功能是?|读走按键|非阻塞查询有无按键|阻塞等待按键|设置键盘重复率|B|查询用 01h(ZF 指示), 读走用 00h —— 游戏循环必背"
"段地址 2000h、偏移地址 1F60h 对应的物理地址是?|21F60h|2000F60h|3F60h|21F6h|A|20000h + 1F60h = 21F60h"
"8 位除法 div bl 的商和余数分别在?|AX 和 DX|AL 和 AH|AH 和 AL|DX 和 AX|B|AX ÷ BL → 商 AL 余 AH; 打印两位数的经典招"
"源操作数 [bx+si+8] 的寻址方式是?|直接寻址|寄存器间接寻址|基址变址寻址|相对寻址|C|BX 基 + SI 变 + 8 位移, 三个零件都齐了"
"想清空整个屏幕, 最合适的做法是?|int 21h 9号|int 10h 6号(al=0)|int 16h 0号|int 21h 4Ch|B|10h 的 6 号滚屏, al=0 就是全屏刷空"
)

echo "======================================================"
echo "    8086 汇编 快问快答   (共 ${#Q[@]} 题)"
echo "    输入 A/B/C/D 回车作答 | 直接回车=看答案 | q=退出"
echo "======================================================"
read -r -p "准备好了按回车开始..." _

score=0; wrong=0; done_n=0; skip=0
n=0
for item in "${Q[@]}"; do
    n=$((n+1))
    IFS='|' read -r text a b c d ans exp <<< "$item"
    echo
    echo "--- 第 $n 题 / ${#Q[@]} ---"
    echo "$text"
    echo "  A. $a"
    echo "  B. $b"
    echo "  C. $c"
    echo "  D. $d"
    read -r -p "你的答案: " u || break
    u=$(echo "$u" | tr 'a-z' 'A-Z' | tr -d ' ')
    if [ "$u" = "q" ]; then
        break
    fi
    if [ -z "$u" ]; then
        echo "  (跳过) 正确答案: $ans"
        skip=$((skip+1))
    elif [ "$u" = "$ans" ]; then
        echo "  ✔ 答对!"
        score=$((score+1))
    else
        echo "  ✘ 不对, 正确答案是 $ans"
        wrong=$((wrong+1))
    fi
    echo "  解析: $exp"
    done_n=$((done_n+1))
done

echo
echo "======================================================"
echo "  成绩单: 答对 $score 题 / 答错 $wrong 题 / 跳过 $skip 题 (共做了 $done_n/${#Q[@]})"
if   [ "$score" -ge 22 ]; then echo "  评级: 满分预定! 这水平可以直接去考试了 ★★★★★"
elif [ "$score" -ge 17 ]; then echo "  评级: 很扎实! 把错题的解析再消化一遍 ★★★★"
elif [ "$score" -ge 12 ]; then echo "  评级: 不错, 建议把错题对应的 LAB 例子重新跑一遍 ★★★"
elif [ "$score" -ge 6  ]; then echo "  评级: 基础还虚, 从 L01-L06 顺着敲一遍再来 ★★"
else                         echo "  评级: 别慌, 先做 LAB 前六课, 一边敲一边看注释 ★"
fi
echo "======================================================"
